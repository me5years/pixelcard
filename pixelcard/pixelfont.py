def text_width(s, font=FONT5x7, spacing=1):
    if not s:
        return 0
    w = 0
    for ch in s:
        g = font.get(ch) or font.get(ch.upper()) or font.get("?")
        w += len(g[0]) + spacing
    return w - spacing


def font_height(font=FONT5x7):
    return len(next(iter(font.values())))
